CREATE TABLE IF NOT EXISTS ADMIN_USER (
  Admin_ID VARCHAR(20) NOT NULL,
  Admin_Name VARCHAR(100) NOT NULL,
  Email VARCHAR(254) NOT NULL,
  Password_Hash VARCHAR(255) NOT NULL,
  Created_At TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (Admin_ID),
  UNIQUE KEY uq_admin_user_email (Email)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE IF NOT EXISTS ADMIN_SESSION (
  Session_ID CHAR(36) NOT NULL,
  Admin_ID VARCHAR(20) NOT NULL,
  Expires_At TIMESTAMP NOT NULL,
  Created_At TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (Session_ID),
  KEY ix_admin_session_admin_id (Admin_ID),
  KEY ix_admin_session_expires_at (Expires_At),
  CONSTRAINT fk_admin_session_admin
    FOREIGN KEY (Admin_ID) REFERENCES ADMIN_USER (Admin_ID)
    ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
